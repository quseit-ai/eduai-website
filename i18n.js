function tr(s, lang) {
  if (lang === 'en') return I18N_EN[s] || s;
  if (lang === 'zh-TW') return ccTW ? ccTW(s) : s;
  return s;
}

function applyLang(lang) {
  // 正文文本节点
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT, {
    acceptNode: n => n.nodeValue.trim() ? NodeFilter.FILTER_ACCEPT : NodeFilter.FILTER_REJECT
  });
  const nodes = [];
  while (walker.nextNode()) nodes.push(walker.currentNode);
  nodes.forEach(n => {
    if (!ORIG.has(n)) ORIG.set(n, n.nodeValue);
    const orig = ORIG.get(n), t = orig.trim();
    n.nodeValue = orig.replace(t, tr(t, lang));
  });
  // 图片 alt
  document.querySelectorAll('img[alt]').forEach(img => {
    if (!img.dataset.i18nAlt) img.dataset.i18nAlt = img.getAttribute('alt');
    img.setAttribute('alt', tr(img.dataset.i18nAlt, lang));
  });
  // 标题与描述
  document.title = tr(META_ORIG.title, lang);
  if (metaDesc) metaDesc.content = tr(META_ORIG.desc, lang);
  // <html lang> 与切换器状态
  document.documentElement.lang = lang === 'en' ? 'en' : lang;
  document.querySelectorAll('.lang-switch button').forEach(b =>
    b.classList.toggle('active', b.dataset.lang === lang));
}

function setLang(lang) {
  localStorage.setItem(LANG_KEY, lang);
  applyLang(lang);
}

// 默认英文；读取记忆语言
applyLang(localStorage.getItem(LANG_KEY) || 'en');
